export const AccountErrorCode = {
  UNAUTHENTICATED: "UNAUTHENTICATED",
  FORBIDDEN: "FORBIDDEN",
  PROFILE_UPDATE_FAILED: "PROFILE_UPDATE_FAILED",
  EMAIL_ALREADY_EXISTS: "EMAIL_ALREADY_EXISTS",
  CURRENT_PASSWORD_INVALID: "CURRENT_PASSWORD_INVALID",
  PASSWORD_VALIDATION_FAILED: "PASSWORD_VALIDATION_FAILED",
  TWO_FACTOR_INVALID: "TWO_FACTOR_INVALID",
  SESSION_NOT_FOUND: "SESSION_NOT_FOUND",
  SESSION_REVOKE_FAILED: "SESSION_REVOKE_FAILED",
  NOTIFICATION_NOT_FOUND: "NOTIFICATION_NOT_FOUND",
  SUPPORT_TICKET_NOT_FOUND: "SUPPORT_TICKET_NOT_FOUND",
  SUPPORT_REPLY_FAILED: "SUPPORT_REPLY_FAILED",
  ACCOUNT_SUSPENDED: "ACCOUNT_SUSPENDED",
  EXPORT_FAILED: "EXPORT_FAILED",
  DELETION_REQUEST_FAILED: "DELETION_REQUEST_FAILED",
  RATE_LIMITED: "RATE_LIMITED",
} as const;

export type AccountErrorCode = (typeof AccountErrorCode)[keyof typeof AccountErrorCode];

export function accountError(
  code: AccountErrorCode,
  message: string,
  status = 400,
): { error: string; code: AccountErrorCode; status: number } {
  return { error: message, code, status };
}
